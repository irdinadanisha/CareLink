export function getLanguageLabel(language: Language) {
  return languageOptions.find((option) => option.code === language)?.label ?? "English";
}

export function isLanguage(value: string | null): value is Language {
  return value === "en" || value === "ms" || value === "zh" || value === "ta";
}

export function translateToMalay(value: string | null | undefined) {
  return translate(value, "ms");
}

export function translate(value: string | number | null | undefined, language: Language) {
  if (value === null || value === undefined) return "";
  const text = String(value);
  const trimmed = text.trim();
  if (!trimmed) return text;
  if (language === "en") return text;
  let translated = dictionaries[language][trimmed];
  if (!translated) {
    translated = fallbacks[language].reduce(
      (current, [pattern, replacement]) => current.replace(pattern, replacement),
      trimmed,
    );
  }
  const start = text.match(/^\s*/)?.[0] ?? "";
  const end = text.match(/\s*$/)?.[0] ?? "";
  return `${start}${translated}${end}`;
}

const originals = new WeakMap<Node, string>();

function translateElement(root: ParentNode, language: Language) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  let node: Node | null;
  while ((node = walker.nextNode())) {
    const parent = node.parentElement;
    if (!parent || parent.closest("script,style,.message-row.user,.original"))
      continue;
    if (!originals.has(node)) originals.set(node, node.nodeValue ?? "");
    const original = originals.get(node) ?? "";
    const next = translate(original, language);
    if (node.nodeValue !== next) node.nodeValue = next;
  }
  root.querySelectorAll?.("[placeholder],[aria-label]").forEach((element) => {
    for (const attribute of ["placeholder", "aria-label"]) {
      const key = `data-i18n-${attribute}`;
      const current = element.getAttribute(attribute);
      if (current && !element.hasAttribute(key))
        element.setAttribute(key, current);
      const original = element.getAttribute(key);
      if (original)
        element.setAttribute(
          attribute,
          translate(original, language),
        );
    }
  });
}

export function applyLanguage(language: Language) {
  document.documentElement.lang = language;
  translateElement(document.body, language);
  const observer = new MutationObserver((mutations) =>
    mutations.forEach((mutation) => {
      if (mutation.type === "characterData") {
        const node = mutation.target;
        const parent = node.parentElement;
        if (
          !parent ||
          parent.closest("script,style,.message-row.user,.original")
        )
          return;
        const current = node.nodeValue ?? "";
        const stored = originals.get(node);
        if (!stored || current !== translate(stored, language))
          originals.set(node, current);
        const original = originals.get(node) ?? current;
        const next = translate(original, language);
        if (current !== next) node.nodeValue = next;
        return;
      }
      mutation.addedNodes.forEach((node) => {
        if (node.nodeType === Node.TEXT_NODE && node.parentElement) {
          if (!originals.has(node)) originals.set(node, node.nodeValue ?? "");
          const original = originals.get(node) ?? "";
          const next = translate(original, language);
          if (node.nodeValue !== next) node.nodeValue = next;
        } else if (node instanceof Element) translateElement(node, language);
      });
    }),
  );
  observer.observe(document.body, {
    childList: true,
    characterData: true,
    subtree: true,
  });
  return () => observer.disconnect();
}
